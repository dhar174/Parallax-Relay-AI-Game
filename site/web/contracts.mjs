export const roles=['SPECTRA','PYRA','FLUX'];
export const conditions=['full','reduced','disabled','withheld','no_images'];
export const conditionRounds=name=>name==='disabled'?0:name==='reduced'?1:2;
function configObject(value,properties,required,where){
 if(value===null||typeof value!=='object'||Array.isArray(value)||![Object.prototype,null].includes(Object.getPrototypeOf(value)))throw Error('Invalid '+where+': expected an object.');
 if(Object.keys(value).some(key=>!Object.hasOwn(properties,key)))throw Error('Invalid '+where+': unknown setting.');
 if(required.some(key=>!Object.hasOwn(value,key)))throw Error('Invalid '+where+': missing required setting.');
}
export function validate(config,contract,live=false){
 const defs=contract.schema.$defs;
 configObject(config,contract.schema.properties,contract.schema.required??[],'configuration');
 const match=config.match===undefined?{}:config.match;
 configObject(match,defs.MatchSettings.properties,defs.MatchSettings.required??[],'match');
 const defaults=Object.fromEntries(Object.entries(defs.MatchSettings.properties).map(([key,s])=>[key,s.default]));
 const normalized={match:{...defaults,...match},players:{}};
 if(match.condition!=null&&!Object.hasOwn(match,'communication_rounds'))normalized.match.communication_rounds=conditionRounds(match.condition);
 for(const [key,s] of Object.entries(defs.MatchSettings.properties)){
  const value=normalized.match[key];
  if(key==='room_id'){if(!(contract.rooms??[{id:'split_span',split:'development'}]).some(r=>r.id===value&&r.split==='development'))throw Error('Select a development room. Held-out execution requires a registered campaign.');continue;}
  if(key==='condition'){if(value!==null&&!conditions.includes(value))throw Error('Invalid condition');continue;}
  if(key==='max_estimated_cost_usd'){if(value!==null&&!(Number.isFinite(value)&&value>0))throw Error('Enter a positive spending limit.');continue;}
  if(!Number.isFinite(value)||(s.type==='integer'&&!Number.isInteger(value))||(s.minimum!==undefined&&value<s.minimum)||(s.maximum!==undefined&&value>s.maximum)||(s.exclusiveMinimum!==undefined&&value<=s.exclusiveMinimum)||(s.enum&&!s.enum.includes(value)))throw Error('Invalid '+key);
 }
 if(normalized.match.condition!==null&&normalized.match.communication_rounds!==conditionRounds(normalized.match.condition))throw Error('Conflicting condition and communication_rounds');
 configObject(config.players,Object.fromEntries(roles.map(r=>[r,true])),roles,'players');
 for(const role of roles){
  const p=config.players[role];
  configObject(p,defs.PlayerSettings.properties,defs.PlayerSettings.required??[],'players.'+role);
  if(!defs.PlayerSettings.properties.provider.enum.includes(p.provider))throw Error('Unsupported provider');
  for(const key of ['model_env','api_key_env'])if(typeof p[key]!=='string'||!/^[A-Z_][A-Z0-9_]{0,127}$/.test(p[key]))throw Error('Invalid environment variable for '+role);
  const pricing=p.pricing===undefined?null:p.pricing;
  if(pricing!==null){
   configObject(pricing,defs.Rates.properties,defs.Rates.required,'players.'+role+'.pricing');
   if(!['input_per_million','output_per_million'].every(key=>Number.isFinite(pricing[key])&&pricing[key]>0))throw Error('Pricing must be positive for '+role);
  }
  if(normalized.match.max_estimated_cost_usd!==null&&pricing===null)throw Error('The spending guard requires pricing for all players.');
  normalized.players[role]={...p,pricing};
 }
 if(live&&normalized.match.max_estimated_cost_usd===null)throw Error('Set a spending guard before approving a live plan.');
 return normalized;
}
export function toml(c){
 const rows=['# Parallax Relay configuration generated by the experiment workbench','[match]'];
 for(const [k,v] of Object.entries(c.match))if(v!=null)rows.push(k+' = '+JSON.stringify(v));
 for(const role of roles){
  const p=c.players[role];rows.push('','[players.'+role+']');
  for(const k of ['provider','model_env','api_key_env'])if(p[k]!=null)rows.push(k+' = '+JSON.stringify(p[k]));
  if(p.pricing){rows.push('[players.'+role+'.pricing]');for(const [k,v]of Object.entries(p.pricing))if(v!=null)rows.push(k+' = '+v);}
 }
 return rows.join('\n')+'\n';
}
export function checkRun(data){
 const field=(value,path,test,expected)=>{
  if(!test(value))throw Error('Invalid '+path+': expected '+expected+'.');
 };
 const object=(value,path)=>field(value,path,v=>v!==null&&typeof v==='object'&&!Array.isArray(v),'an object');
 const string=(value,path)=>field(value,path,v=>typeof v==='string','a string');
 const boolean=(value,path)=>field(value,path,v=>typeof v==='boolean','a boolean');
 const count=(value,path,min=0)=>field(value,path,v=>Number.isSafeInteger(v)&&v>=min,'an integer >= '+min);
 const array=(value,path)=>field(value,path,Array.isArray,'an array');

 object(data,'run');
 object(data.manifest,'manifest');
 field(data.manifest.schema_version,'manifest.schema_version',v=>v===2||v===3,'schema version 2 or 3');
 field(data.manifest.mode,'manifest.mode',v=>v==null||['mock','live','programmatic','unknown'].includes(v),'mock, live, programmatic or unknown');
 if(data.manifest.room!=null)string(data.manifest.room,'manifest.room');
 object(data.result,'result');
 const result=data.result;
 field(result.schema_version,'result.schema_version',v=>v===data.manifest.schema_version,'the manifest schema version');
 for(const key of ['win','loss','completed'])boolean(result[key],'result.'+key);
 count(result.turns,'result.turns');
 string(result.stop_reason,'result.stop_reason');
 if(!result.completed){
  field(result.scores,'result.scores',v=>v===null,'null for an incomplete run');
 }else{
  object(result.scores,'result.scores');
  for(const role of roles)field(result.scores[role],'result.scores.'+role,Number.isFinite,'a finite number');
 }
 object(result.budget,'result.budget');
 for(const key of ['calls_started','max_calls','reported_input_tokens','reported_output_tokens','unknown_usage_calls']){
  count(result.budget[key],'result.budget.'+key);
 }
 field(result.budget.estimated_cost_usd,'result.budget.estimated_cost_usd',
  v=>v===null||(Number.isFinite(v)&&v>=0),'null or a nonnegative finite number');
 for(const key of ['known_usage_estimated_usd','retained_estimate_usd','reserved_estimated_usd']){
  if(Object.hasOwn(result.budget,key))field(result.budget[key],'result.budget.'+key,
   v=>v===null||(Number.isFinite(v)&&v>=0),'null or a nonnegative finite number');
 }

 object(data.final_state,'final_state');
 let checkState=()=>{};
 if(data.manifest.schema_version===3){
  const p=data.manifest.provenance;object(p,'provenance');
  field(p.schema_version,'provenance.schema_version',v=>v===3,'schema version 3');
  const identity=p.inputs?.room?.value;object(identity,'room identity');
  const room=identity.definition;object(room,'room definition');
  string(room.id,'room.id');count(room.width,'room.width',3);
  field(room.width,'room.width',v=>v<=13,'width <= 13');
  field(data.manifest.room,'manifest.room',v=>v===room.id&&identity.id===room.id,'the recorded room id');
  field(room.version,'room.version',v=>v===1&&identity.version===v,'room version 1');
  count(room.deadline,'room.deadline',1);array(room.bridges,'room.bridges');array(room.cells,'room.cells');
  const position=(v,path)=>{count(v,path);field(v,path,n=>n<room.width,'a position inside the room');};
  for(const key of ['exit','shard'])position(room[key],'room.'+key);
  room.cells.forEach(v=>position(v,'room cell'));
  room.bridges.forEach(b=>{object(b,'room bridge');position(b.motor,'room motor');array(b.gap,'room gap');b.gap.forEach(v=>position(v,'room gap position'));});
  checkState=(state,path)=>{
   object(state,path);
   field(state.room_id,path+'.room_id',v=>v===room.id,'the recorded room');
   field(state.room_version,path+'.room_version',v=>v===room.version,'the recorded room version');
   for(const key of ['turn','energy','coolant'])count(state[key],path+'.'+key);
   field(state.turn,path+'.turn',v=>v<=room.deadline,'a turn within the deadline');
   object(state.robots,path+'.robots');
   for(const role of roles){const robot=state.robots[role];object(robot,path+'.robot');field(robot.role,path+'.role',v=>v===role,'the matching role');position(robot.x,path+'.position');count(robot.damage,path+'.damage');}
   const keys=room.bridges.map((_,i)=>'bridge_'+i);
   object(state.motor_heats,path+'.motor_heats');
   field(Object.keys(state.motor_heats),path+'.motor_heats',v=>v.length===keys.length&&keys.every(k=>Object.hasOwn(state.motor_heats,k)),'the room motors');
   for(const heat of Object.values(state.motor_heats))count(heat,path+'.heat');
   for(const [key,allowed] of [['powered_bridges',keys],['collected_cells',room.cells]]){array(state[key],path+'.'+key);field(state[key],path+'.'+key,v=>new Set(v).size===v.length&&v.every(x=>allowed.includes(x)),'unique room references');}
   for(const key of ['exit_unlocked','shard_collected','win','loss'])boolean(state[key],path+'.'+key);
   field(state.win,path+'.win',v=>!v||(!state.loss&&state.exit_unlocked&&roles.every(r=>state.robots[r].x===room.exit)&&(!room.requires_shard||state.shard_collected)),'a consistent room victory');
   array(state.events,path+'.events');state.events.forEach(v=>string(v,path+'.event'));
  };
  checkState(identity.initial_state,'room initial_state');
  checkState(data.final_state,'final_state');
 }
 array(data.calls,'calls');
 data.calls.forEach((call,i)=>{
  const path='calls['+i+']';
  object(call,path);
  for(const key of ['role','phase','status'])string(call[key],path+'.'+key);
  count(call.turn,path+'.turn');
  count(call.attempt,path+'.attempt',1);
 });
 array(data.phases,'phases');
 data.phases.forEach((phase,i)=>object(phase,'phases['+i+']'));
 array(data.replay,'replay');
 data.replay.forEach((turn,i)=>{
  const path='replay['+i+']';
  object(turn,path);
  count(turn.turn,path+'.turn',1);
  object(turn.state_after,path+'.state_after');
  checkState(turn.state_after,path+'.state_after');
  count(turn.state_after.energy,path+'.state_after.energy');
  object(turn.observations,path+'.observations');
  for(const role of roles){
   const observation=turn.observations[role],where=path+'.observations.'+role;
   object(observation,where);
   if(observation.image!==undefined)string(observation.image,where+'.image');
  }
  array(turn.communications,path+'.communications');
  turn.communications.forEach((message,j)=>{
   const where=path+'.communications['+j+']';
   object(message,where);
   for(const key of ['role','phase','text'])string(message[key],where+'.'+key);
  });
  array(turn.events,path+'.events');
 });
 if(data.images!==undefined){
  object(data.images,'images');
  for(const value of Object.values(data.images)){
   // Do not include imported names or values in validation errors.
   string(value,'images entry');
  }
 }
 // Validate without projecting: retain optional records and provenance metadata.
 return data;
}
