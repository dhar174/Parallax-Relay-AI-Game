export const roles=['SPECTRA','PYRA','FLUX'];
export function validate(config,contract,live=false){
 const schema=contract.schema.$defs.MatchSettings.properties;
 for(const [key,s] of Object.entries(schema)){
  const value=config.match[key];
  if(key==='max_estimated_cost_usd'){if(value!==null && !(Number.isFinite(value)&&value>0))throw Error('Enter a positive spending limit.');continue;}
  if(!Number.isFinite(value)||(s.type==='integer'&&!Number.isInteger(value))||(s.minimum!==undefined&&value<s.minimum)||(s.maximum!==undefined&&value>s.maximum)||(s.exclusiveMinimum!==undefined&&value<=s.exclusiveMinimum)||(s.enum&&!s.enum.includes(value)))throw Error('Invalid '+key);
 }
 for(const role of roles){const p=config.players[role];
  if(!contract.schema.$defs.PlayerSettings.properties.provider.enum.includes(p.provider))throw Error('Unsupported provider');
  for(const key of ['model_env','api_key_env'])if(!/^[A-Z_][A-Z0-9_]{0,127}$/.test(p[key]))throw Error('Invalid environment variable for '+role);
  if(p.pricing && !Object.values(p.pricing).every(v=>Number.isFinite(v)&&v>0))throw Error('Pricing must be positive for '+role);
  if(config.match.max_estimated_cost_usd!==null&&!p.pricing)throw Error('The spending guard requires pricing for all players.');
 }
 if(live && config.match.max_estimated_cost_usd===null)throw Error('Set a spending guard before approving a live plan.');
 return config;
}
export function toml(c){
 const rows=['# Parallax Relay configuration generated by the experiment workbench','[match]'];
 for(const [k,v] of Object.entries(c.match))if(v!==null)rows.push(k+' = '+JSON.stringify(v));
 for(const role of roles){const p=c.players[role];rows.push('','[players.'+role+']');for(const k of ['provider','model_env','api_key_env'])rows.push(k+' = '+JSON.stringify(p[k]));if(p.pricing){rows.push('[players.'+role+'.pricing]');for(const [k,v]of Object.entries(p.pricing))rows.push(k+' = '+v);}}
 return rows.join('\n')+'\n';
}
export function checkRun(data){
 if(data.manifest?.schema_version!==2||data.result?.schema_version!==2||!['mock','live'].includes(data.manifest.mode)||!Array.isArray(data.calls)||!Array.isArray(data.replay)||!Array.isArray(data.phases)||!data.result.budget)throw Error('Select a complete schema-version-2 run directory or workbench export.');
 for(const turn of data.replay)if(!Number.isInteger(turn.turn)||!turn.observations||!turn.state_after||!Array.isArray(turn.communications))throw Error('Malformed turn record');
 return data;
}
